let currentLang = localStorage.getItem('ski_lang') || 'ko';

export const getLang = () => currentLang;

export const setLang = (lang) => {
  if (i18n[lang]) {
    currentLang = lang;
    localStorage.setItem('ski_lang', lang);
  }
};

export const t = (key) => {
  const dict = i18n[currentLang] || i18n.ko;
  return dict[key] || key;
};

